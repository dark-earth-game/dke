#!/bin/sh
# Regenerate src/levels/levels_table.h from the ported levels present
# (src/levels/lieuNN.c defining lieuNN_fonction_editor).
cd "$(dirname "$0")/../src/levels" || exit 1
{
    echo "/* levels_table.h — generated by tools/gen_levels.sh; do not edit. */"
    echo
    for f in lieu[0-9][0-9].c; do
        n=${f#lieu}; n=${n%.c}
        echo "i32 lieu${n}_fonction_editor(i32 op, lieu_state_t *state, i32 arg, i32 arg2);"
    done
    echo
    echo "static const lieu_entry_t k_level_entry[100] = {"
    for f in lieu[0-9][0-9].c; do
        n=${f#lieu}; n=${n%.c}
        echo "    [$((10#$n))] = lieu${n}_fonction_editor,"
    done
    echo "};"
} > levels_table.h
